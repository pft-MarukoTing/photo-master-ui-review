"""Stage 2.0 migration acceptance, authored from upload/user/job scenarios.

Uses real Flask routes and worker entry points, with queue/storage/model I/O
replaced at their boundaries. Expected states and IDs are product contracts,
not output generated by the production validation or matching algorithm.
Can also run against the donor via PYTHONPATH, without copying its implementation.
"""

