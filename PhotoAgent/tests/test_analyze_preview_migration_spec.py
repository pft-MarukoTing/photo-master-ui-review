def photo(color=(120, 140, 160), orientation=None):
    output = io.BytesIO()
    image = Image.new('RGB', (96, 64), color)
    if orientation is not None:
        exif = image.getexif()
        exif[274] = orientation
        image.save(output, 'JPEG', exif=exif)
    else:
        image.save(output, 'PNG')
    return output.getvalue()


class AnalyzePreviewMigrationAcceptance(unittest.TestCase):
    def setUp(self):
        route_tests.ChatRoutesTest.setUp(self)
        self.data = photo()
        self.raw_jobs = {}
        self.uploads = []
        self.artifacts = {}
        self.enqueue_calls = []

        def enqueue(engine, src_content=None, job_id=None):
            job_id = job_id or next(self.next_job)
            for field in ('srcKeys', 'dstKeys'):
                engine[field] = [value.replace('{msg_id}', job_id) for value in engine[field]]
            stored = copy.deepcopy(engine)
            self.raw_jobs[job_id] = {**stored, 'status': 'processing'}
            self.enqueue_calls.append((job_id, stored))
            self.uploads.append(copy.deepcopy(src_content))
            return job_id

        self.switch = patch.object(config, 'ENABLE_CHAT_SUBJECT_PREVIEW', True, create=True)
        self.switch.start()
        self.addCleanup(self.switch.stop)
        for name, replacement in (
            ('enqueue', enqueue),
            ('get_job_info', lambda job_id, **kwargs: self.raw_jobs.get(job_id)),
            ('download_bytes', lambda key, job_id: (self.artifacts.get(key), None)),
        ):
            stub = patch.object(chat, name, replacement)
            stub.start()
            self.addCleanup(stub.stop)

    def start_preview(self, data=None):
        response = self.client.post('/api/photo-agent/chat/previews', data={
            'user': USER, 'image': (io.BytesIO(data or self.data), 'photo.png'),
        })
        self.assertEqual(response.status_code, 202, response.get_json())
        body = response.get_json()
        self.assertEqual(body['source_sha256'], hashlib.sha256(data or self.data).hexdigest())
        return body

    def snapshot(self, preview, state='ready'):
        info = self.raw_jobs[preview['preview_job_id']]
        info['acts'][0]['params']['preview_format_version'] = 1
        box = {'x': .1, 'y': .1, 'w': .3, 'h': .4}
        face_box = {'x': .16, 'y': .16, 'w': .14, 'h': .17}
        coordinate_space = 'exif_transposed_original_normalized'
        classified = {
            'state': 'ready', 'provisional': True, 'coordinate_space': coordinate_space,
            'main_subject_kind': 'person', 'primary_detection_index': 1,
            'summary': '左側人物是主要拍攝對象。',
            'detections': [{'detection_index': 1, 'role': 'included', 'face_readable': True,
                            'label': '左側人物', 'face_box': face_box}],
        } if state == 'ready' else {
            'state': 'unavailable', 'provisional': True, 'coordinate_space': coordinate_space,
            'reason': 'timeout', 'skipped': False,
        }
        context = {'format_version': 1, 'binding': copy.deepcopy(info['acts'][0]['params']['preview_binding']),
                   'src_keys': list(info['srcKeys']), 'coordinate_space': coordinate_space,
                   'image_size': [96, 64],
                   'detections': [{'detection_index': 1, 'box': box, 'face_box': face_box, 'sent_to_model': True}],
                   'subject_preview': classified}
        info['preview_context'] = {**copy.deepcopy(context), 'timing': {'completed_at': time.time()}}
        return context

    def status_response(self, preview, user=USER):
        return self.client.get(f"/api/photo-agent/chat/previews/{preview['preview_job_id']}", query_string={'user': user})

    def submit(self, preview=None, data=None):
        session = route_tests.ChatRoutesTest.new_session(self)
        fields = {'user': USER, 'image': (io.BytesIO(data or self.data), 'photo.png')}
        if preview:
            fields.update({key: preview[key] for key in ('preview_job_id', 'source_sha256')})
        return self.client.post(f'/api/photo-agent/chat/sessions/{session}/photos', data=fields)

    def test_P01_enabled_preview_is_advertised_to_chat(self):
        self.assertTrue(capabilities.describe().get('features', {}).get('subject_preview'), 'Chat must discover Stage 2.0 support')

    def test_P02_select_photo_enqueues_preview_without_formal_analysis_or_history(self):
        with patch.object(image_tools, 'detect_face_boxes', side_effect=AssertionError('Flask must not detect')):
            self.start_preview()
        self.assertEqual(len(self.enqueue_calls), 1)
        self.assertEqual(self.enqueue_calls[0][1]['acts'][0]['params']['stage'], 'analyze_preview')
        self.assertEqual(self.uploads, [[self.data]])
        self.assertEqual(self.history, [])

    def test_P03_queued_preview_reports_pending_without_private_payloads(self):
        preview = self.start_preview()
        body = self.status_response(preview).get_json()
        self.assertEqual(body['state'], 'pending')
        for field in ('acts', 'srcKeys', 'dstKeys', 'preview_context', 'raw_output_text'):
            self.assertNotIn(field, body)

    def test_P04_classification_is_visible_before_artifact_upload_finishes(self):
        preview = self.start_preview()
        self.snapshot(preview)
        with patch.object(chat, 'download_bytes', side_effect=AssertionError('snapshot must not need S3')):
            response = self.status_response(preview)
        self.assertEqual(response.status_code, 200)
        body = response.get_json()
        self.assertEqual((body['status'], body['state'], body['reusable']), ('processing', 'ready', True))
        self.assertEqual([(f['detection_index'], f['label']) for f in body['faces']], [(1, '左側人物')])

    def test_P05_artifact_upload_failure_does_not_erase_completed_preview(self):
        preview = self.start_preview()
        self.snapshot(preview)
        self.raw_jobs[preview['preview_job_id']]['status'] = 'error'
        body = self.status_response(preview).get_json()
        self.assertEqual((body['state'], body['reusable']), ('ready', True))

    def test_P06_timeout_classification_can_still_reuse_detector_geometry(self):
        preview = self.start_preview()
        context = self.snapshot(preview, 'unavailable')
        body = self.status_response(preview).get_json()
        self.assertEqual((body['state'], body['reusable']), ('unavailable', True))
        self.assertEqual(self.submit(preview).status_code, 202)
        params = self.enqueue_calls[-1][1]['acts'][0]['params']
        self.assertEqual(params['precomputed_preview'], context)

    def test_P07_formal_submit_freezes_server_snapshot_and_reuses_source(self):
        preview = self.start_preview()
        context = self.snapshot(preview)
        self.assertEqual(self.submit(preview).status_code, 202)
        engine = self.enqueue_calls[-1][1]
        self.assertIsNone(self.uploads[-1], 'Original must not be uploaded a second time')
        self.assertEqual(engine['srcKeys'], context['src_keys'])
        self.assertEqual(engine['acts'][0]['params']['precomputed_preview'], context)
        self.raw_jobs[preview['preview_job_id']]['preview_context']['subject_preview']['summary'] = 'later mutation'
        self.assertEqual(engine['acts'][0]['params']['precomputed_preview']['subject_preview']['summary'], '左側人物是主要拍攝對象。')

