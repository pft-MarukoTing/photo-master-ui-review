    def test_P22_model_timeout_retries_once_without_formal_analysis(self):
        import pipeline
        import openai_client
        self.assertTrue(hasattr(pipeline, 'analyze_preview_stage'), 'Separate preview stage is required')
        preview = self.start_preview()
        engine = self.raw_jobs[preview['preview_job_id']]
        crop = {'box': {'x': .1, 'y': .1, 'w': .3, 'h': .4},
                'face_box': {'x': .16, 'y': .16, 'w': .14, 'h': .17}, 'bytes': self.data}
        with patch.object(config, 'ENABLE_PREVIEW_LOW_CONFIDENCE_CANDIDATES', False), \
             patch.object(image_tools, 'detect_face_crops', return_value=[crop]), \
             patch.object(openai_client, '_auth_headers', return_value={}), \
             patch.object(openai_client.requests, 'post', side_effect=openai_client.requests.Timeout) as model:
            result = pipeline.analyze_preview_stage(self.data, analysis_model=config.MODELS['analysis'],
                binding=engine['acts'][0]['params']['preview_binding'], src_keys=engine['srcKeys'])
        self.assertEqual(model.call_count, 2)
        self.assertEqual(model.call_args_list[0].kwargs['data'], model.call_args_list[1].kwargs['data'])
        self.assertEqual(result['subject_preview']['state'], 'unavailable')
        self.assertEqual(len(result['detections']), 1)
        self.assertNotIn('subjects', result)

