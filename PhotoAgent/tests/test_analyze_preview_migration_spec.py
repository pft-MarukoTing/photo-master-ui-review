    def test_P19_preview_worker_never_runs_formal_QC_body_or_editor(self):
        preview = self.start_preview()
        snapshot = self.snapshot(preview)
        queue = types.ModuleType('aiserver_utils.queue')
        queue.set_job_info = MagicMock()
        queue.get_job_info = MagicMock()
        with patch.dict(sys.modules, {'aiserver_utils.queue': queue}):
            import job_processor
        self.assertTrue(hasattr(job_processor, 'analyze_preview_stage'), 'Worker must expose the separate Stage 2.0 pipeline')
        events = []
        with tempfile.TemporaryDirectory(dir='/tmp') as directory:
            image = Path(directory) / 'photo.png'
            image.write_bytes(self.data)
            worker = job_processor.PhotoAgentJobProcessor(MagicMock(), MagicMock(), monitor_dst_dir=directory)
            with patch.object(worker, 'download_sources', return_value=[str(image)]), \
                 patch.object(worker, 'upload_artifacts', side_effect=lambda *args: events.append('artifact')), \
                 patch.object(job_processor, 'set_job_info', side_effect=lambda **kwargs: events.append('snapshot')), \
                 patch.object(job_processor, 'analyze_preview_stage', return_value=snapshot) as quick, \
                 patch.object(job_processor, 'analyze_stage', side_effect=AssertionError('No formal analysis')), \
                 patch.object(job_processor, 'review_stage', side_effect=AssertionError('No review')), \
                 patch.object(job_processor, 'finish_stage', side_effect=AssertionError('No edit')):
                result = worker.process_for_api(preview['preview_job_id'], self.raw_jobs[preview['preview_job_id']])
        quick.assert_called_once()
        self.assertEqual(events, ['snapshot', 'artifact'])
        self.assertTrue(result['0_res0']['cusKeys'][0].endswith('/0_res0_preview.json'))

    def test_P20_formal_analysis_must_keep_the_girl_missed_by_the_detector(self):
        # Compatibility gate: pool-photo story, detector finds only the boy.
        # Independent fake vision reply still identifies the photographed girl.
        import openai_client
        self.assertIn('precomputed_preview', __import__('inspect').signature(openai_client.analyze_photo).parameters,
                      'Formal analysis must accept the frozen Stage 2.0 snapshot')
        preview = self.start_preview()
        snapshot = self.snapshot(preview)
        overall = {'photo_summary': '男孩和女孩乘坐水上船', 'recommended_aspect_ratio': 'original',
                   'subjects': [{'label': '男孩', 'is_person': True, 'local_detection_index': 1,
                                 'box': {'x': .1, 'y': .1, 'w': .3, 'h': .4}},
                                {'label': '後方左側女孩', 'is_person': True, 'local_detection_index': -1,
                                 'box': {'x': .6, 'y': .2, 'w': .2, 'h': .4}}],
                   'local_face_review': [{'detection_index': 1, 'is_real_face': True, 'matched_subject_index': 0, 'reason': '主要拍攝對象'}]}
        envelope = {'status': 'completed', 'output_text': json.dumps(overall), 'usage': {'input_tokens': 4, 'output_tokens': 5}}
        skill = MagicMock()
        skill.run.side_effect = lambda analysis, ctx: (analysis, [])
        with patch.object(openai_client, 'detect_face_crops', side_effect=AssertionError('No repeated detection')), \
             patch.object(openai_client, '_post_json', return_value=envelope), \
             patch.object(openai_client, 'ANALYSIS_SKILLS', [skill]), \
             patch.object(openai_client, 'select_analysis_skills', return_value=[skill]):
            try:
                analysis, _ = openai_client.analyze_photo(self.data, precomputed_preview=snapshot)
            except ValueError as exc:
                self.fail(f'Girl must not be rejected solely for lacking a detector ID: {exc}')
        self.assertEqual([(s['label'], s['is_person']) for s in analysis['subjects']], [('男孩', True), ('後方左側女孩', True)])
        self.assertEqual([p['subject_index'] for p in face_people(analysis)], [0, 1])
        self.assertEqual(len(skill.run.call_args.args[0]['subjects']), 2)

