import glob
import os
import numpy as np
import cv2

def get_file_path_list_in_path(path, w_ext=[], wo_ext=[]):
	assert((len(w_ext) >= 0 and len(wo_ext) == 0) or \
		   (len(w_ext) == 0 and len(wo_ext) >= 0))

	file_list = glob.glob(os.path.join(path, '*'))
	filtered_file_list = []
	if len(w_ext) > 0:
		for file in file_list:
			ext = os.path.splitext(file)[-1]
			if ext in w_ext:
				filtered_file_list.append(file)
	elif len(wo_ext) > 0:
		for file in file_list:
			ext = os.path.splitext(file)[-1]
			if ext in wo_ext:
				continue
			filtered_file_list.append(file)
	else:
		filtered_file_list = file_list
	return sorted(filtered_file_list)

def pasting_back_to_source_image(src_image, image, transformed_boundary_map):
	src_image = src_image.astype(np.uint8)
	image = image.astype(np.uint8)
	transformed_boundary_map = transformed_boundary_map.astype(np.uint8)
	return np.where(transformed_boundary_map == 255, image, src_image).astype(np.uint8)

def pasting_back_inpainted_area(src_image, image, transformed_mask, dilate_size=5, feather_sigma=2.0, keep_map=None):
	# Pastes only the inpainted area back: outside it the patch is resampled twice and regenerated by CoordFill,
	# which softens skin texture and lashes. The mask is grown a little to cover CoordFill's boundary blending and feathered.
	mask = transformed_mask if transformed_mask.ndim == 2 else np.max(transformed_mask, axis=2)
	mask = (mask > 127).astype(np.uint8)
	mask = cv2.dilate(mask, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (dilate_size, dilate_size)))
	alpha = cv2.GaussianBlur(mask.astype(np.float32), (0, 0), feather_sigma)
	if keep_map is not None:
		# keep_map: 1 keeps src_image even inside the mask
		alpha = alpha * (1.0 - keep_map)
	alpha = alpha[..., None]
	return np.clip(alpha * image.astype(np.float32) + (1.0 - alpha) * src_image.astype(np.float32), 0.0, 255.0).astype(np.uint8)

def padding_to_rectangle(image, align_points=[]):
	height, width, channel = image.shape
	if height != width:
		larger_size, smaller_size = max(height, width), min(height, width)
		zero_image = np.zeros((larger_size, larger_size, channel))
		if larger_size == height:
			zero_image[::, (larger_size - smaller_size) // 2:(larger_size - smaller_size) // 2+smaller_size] = image
			if len(align_points) > 0:
				align_points[..., 0] += (larger_size - smaller_size) // 2
		else:
			zero_image[(larger_size - smaller_size) // 2:(larger_size - smaller_size) // 2+smaller_size, ::] = image
			if len(align_points) > 0:
				align_points[..., 1] += (larger_size - smaller_size) // 2
		image = zero_image
	image = image.astype(np.uint8)
	if len(align_points) > 0:
		return image, height, width, align_points
	else:
		return image, height, width

def reverse_padding_to_rectangle(image, original_height, original_width, align_points=[]):
	channel = image.shape[-1]
	if original_height != original_width:
		larger_size, smaller_size = max(original_height, original_width), min(original_height, original_width)
		zero_image = np.zeros((original_height, original_width, channel))
		if larger_size == original_height:
			zero_image = image[::, (larger_size - smaller_size) // 2:(larger_size - smaller_size) // 2+smaller_size]
			if len(align_points) > 0:
				align_points[..., 0] -= (larger_size - smaller_size) // 2
		else:
			zero_image = image[(larger_size - smaller_size) // 2:(larger_size - smaller_size) // 2+smaller_size, ::]
			if len(align_points) > 0:
				align_points[..., 1] -= (larger_size - smaller_size) // 2
		image = zero_image
	image = image.astype(np.uint8)
	if len(align_points) > 0:
		return image, align_points
	else:
		return image

def resize_with_aspect_ratio(original_image, target_height):
	original_height, original_width, original_channel = original_image.shape
	original_aspect_ratio = original_width/original_height
	if original_height != target_height:
		interpolation_type = cv2.INTER_AREA if original_height > target_height else cv2.INTER_LINEAR
		image = cv2.resize(original_image, (int(target_height*original_aspect_ratio), target_height), interpolation=interpolation_type)
	else:
		image = original_image
	return image

def sharpen_filter(image):
	kernel = np.array([[0, -1, 0], [-1, 5, -1], [0, -1, 0]]) 
	sharpened_image = cv2.filter2D(image, -1, kernel) 
	sharpened_image = np.clip(sharpened_image, 0.0, 255.0)
	return sharpened_image